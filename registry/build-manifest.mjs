// Rebuilds registry/components.json from the Slint sources and the GPUI block
// sources. Rust toolkits without files yet stay in the manifest with an empty
// component map. Adding one is a new entry here, not a new CLI release.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ui = path.join(root, 'crates/slint-component/ui');

function importsOf(file) {
  const text = fs.readFileSync(path.join(ui, file), 'utf8');
  return [...text.matchAll(/from\s+"([^"]+\.slint)"/g)].map((match) => path.basename(match[1]));
}

// `build.rs` writes `gallery-catalog.slint` into this folder whenever a gallery
// is built, and it is not tracked. Including it would make the manifest depend
// on whether anyone had run a gallery build in that checkout, and would offer a
// component whose source resolves to nothing over raw GitHub.
const EXPECTED_EXCLUDED = ['gallery-catalog.slint', 'gallery.slint'];

function isGenerated(file) {
  return /Generated by build\.rs/.test(fs.readFileSync(path.join(ui, file), 'utf8').slice(0, 400));
}

const allSlint = fs.readdirSync(ui).filter((name) => name.endsWith('.slint'));
const slintFiles = allSlint.filter((name) => name !== 'gallery.slint' && !isGenerated(name));

const excluded = allSlint.filter((name) => !slintFiles.includes(name));
const unexpected = excluded.filter((name) => !EXPECTED_EXCLUDED.includes(name));
if (unexpected.length > 0) {
  throw new Error(
    `Unexpected generated .slint files: ${unexpected.join(', ')}. ` +
      `Add them to EXPECTED_EXCLUDED only after checking they are build output, not components.`,
  );
}
const icons = fs
  .readdirSync(path.join(ui, 'icons'))
  .filter((name) => name.endsWith('.svg'))
  .sort();

// Walks what a file imports until every file it reaches has been seen, and
// returns the sorted set: everything a copy has to carry for the start file to
// compile. Slint reaches a sibling with `import`, iced with `super::`, so both
// feed the walk and it stays one mechanism.
function closure(start, importsOfFile) {
  const seen = new Set();
  const pending = [start];
  while (pending.length) {
    const file = pending.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    for (const imported of importsOfFile(file)) pending.push(imported);
  }
  return [...seen].sort();
}

const slint = {
  default_target_dir: 'ui/components',
  components: {},
};
for (const file of slintFiles.sort()) {
  const name = file.replace(/\.slint$/, '');
  const files = closure(file, importsOf).map((imported) => ({
    src: `crates/slint-component/ui/${imported}`,
    target: imported,
  }));
  if (files.some((item) => item.target === 'icon.slint')) {
    for (const icon of icons) {
      files.push({
        src: `crates/slint-component/ui/icons/${icon}`,
        target: `icons/${icon}`,
      });
    }
  }
  slint.components[name] = files;
}

const rust = (dir) => ({
  default_target_dir: dir,
  mod_file: `${dir}/mod.rs`,
  components: {},
});

// The GPUI components themselves ship in the `gpui-kit` crate, so what the
// registry copies for this framework is a composed screen: one file per block,
// which the CLI writes into the app and reaches with a `pub mod` line. The name
// is the registry key, the file name and the module name at once.
const GPUI_BLOCKS = ['dock', 'settings', 'sidebar'];
const gpui = rust('src/components');
for (const name of GPUI_BLOCKS) {
  if (!/^[a-z][a-z0-9_]*$/.test(name)) {
    // `uni-kit add` refuses a module name it cannot write as `pub mod <name>;`,
    // so a name the CLI would reject must not reach the manifest.
    throw new Error(`GPUI block "${name}" is not a valid Rust module name.`);
  }
  const src = `crates/blocks/src/${name}.rs`;
  if (!fs.existsSync(path.join(root, src))) {
    throw new Error(
      `GPUI block "${name}" has no source at ${src}. ` +
        `A manifest entry whose source resolves to nothing installs a broken set, ` +
        `so the file is required before the entry exists.`,
    );
  }
  gpui.components[name] = [{ src, target: `${name}.rs`, module: name }];
}

// iced components are Rust source a project copies in, like Slint's, so every
// entry names real files: the component, every sibling component it composes,
// and the theme they read. The theme is shared, so the CLI writes it once
// however many components are installed.
//
// A component reaches the theme as `super::theme`, which is why the installed
// directory can be moved or renamed without editing anything: the files are
// siblings wherever they land.
const icedUi = path.join(root, 'crates/iced-component/src/components');

// A component that composes a sibling names it as `super::<module>`, and the
// copied file only compiles with that sibling beside it. Installing
// `number-input` used to write `number_input.rs` and `theme.rs` alone, and the
// project then failed on a missing `input.rs` and `button.rs`. Which siblings
// those are is read from the source, so a component that grows a composition
// grows its install with it.
//
// Doc comments link siblings too — ``[`Button`](super::button)`` — without
// depending on them, so comments come out first: a link must not drag a file
// into every entry that merely mentions it. A name only counts as a sibling
// when a file of that name exists, which keeps `use super::<item>` inside a
// file's own test module from naming a component. The theme is reached this way
// by nearly every component and is added to each entry once, below.
function componentImportsOf(file) {
  const text = fs
    .readFileSync(path.join(icedUi, file), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1');
  return [...text.matchAll(/\bsuper::([a-z_][a-z0-9_]*)/g)]
    .map((match) => `${match[1]}.rs`)
    .filter(
      (imported) =>
        imported !== 'theme.rs' && fs.existsSync(path.join(icedUi, imported)),
    );
}

const iced = rust('src/components');
if (fs.existsSync(icedUi)) {
  const theme = 'crates/iced-component/src/components/theme.rs';
  if (!fs.existsSync(path.join(root, theme))) {
    throw new Error(`iced components are installed with their theme, and ${theme} does not exist.`);
  }
  const files = fs
    .readdirSync(icedUi)
    .filter((name) => name.endsWith('.rs') && name !== 'theme.rs' && name !== 'mod.rs')
    .sort();
  // A component that reaches past iced to a crate iced merely re-exports needs
  // that crate named in the application's manifest too. Which components those
  // are is read from the sources rather than listed by hand, so installing one is
  // enough to know what it needs.
  const needsExtra = {};
  for (const file of files) {
    const module = file.replace(/\.rs$/, '');
    if (!/^[a-z][a-z0-9_]*$/.test(module)) {
      // A registry key may hold a hyphen, a module name may not. The key the
      // site and the CLI use is the module with underscores back to hyphens, so
      // `description_list.rs` installs as `npx uni-kit add iced description-list`.
      throw new Error(
        `iced component "${module}" is not a valid Rust module name. ` +
          `Name the file after the registry key with hyphens as underscores.`,
      );
    }
    const name = module.replace(/_/g, '-');
    if (iced.components[name]) {
      // `dropdown_button` and `dropdown-button` would install over each other.
      throw new Error(`iced components "${module}" and another file both map to the registry key "${name}".`);
    }
    const src = `crates/iced-component/src/components/${file}`;
    // The component and every sibling it composes, sorted by the closure, then
    // the theme. A component with no sibling keeps the entry it had.
    iced.components[name] = [
      ...closure(file, componentImportsOf).map((imported) => ({
        src: `crates/iced-component/src/components/${imported}`,
        target: imported,
        module: imported.replace(/\.rs$/, ''),
      })),
      { src: theme, target: 'theme.rs', module: 'theme' },
    ];
    const source = fs.readFileSync(path.join(root, src), 'utf8');
    const extra = ['iced_core'].filter((crate) => new RegExp(`\\b${crate}::`).test(source));
    if (extra.length > 0) needsExtra[name] = extra;
  }

  // The versions come from the crate's own manifest, so the hint the CLI prints
  // and the crate that compiles are the same statement.
  const crateManifest = fs.readFileSync(path.join(root, 'crates/iced-component/Cargo.toml'), 'utf8');
  const extraVersions = {};
  for (const crate of new Set(Object.values(needsExtra).flat())) {
    const declared = crateManifest.match(new RegExp(`^\\s*${crate}\\s*=\\s*"([^"]+)"`, 'm'))?.[1];
    if (!declared) {
      throw new Error(
        `iced component source uses \`${crate}\` but crates/iced-component/Cargo.toml does not declare it.`,
      );
    }
    extraVersions[crate] = declared;
  }
  if (Object.keys(needsExtra).length > 0) {
    iced.needs_extra = needsExtra;
    iced.extra_versions = extraVersions;
  }
}

// NSH components are TSX source an application copies into `src/components`,
// like Slint's `.slint` files and iced's `.rs` files. They import their siblings
// with `./name`; the theme and its token table are appended to every entry, and
// `theme.json` gives `nsh/ui/mobile` the same palette. There is no module file
// to declare: the application imports the component it wants directly.
const nshUi = path.join(root, 'crates/nsh-component/src/components');
const nsh = {
  default_target_dir: 'src/components',
  // NSH is developed on its own branch before it lands on `main`; a published
  // package can still read these sources from the right ref if its bundled
  // copy is unavailable.
  source_ref: 'nsh',
  components: {},
};

/** Resolve an extensionless relative import to a file in the component folder. */
function resolveNshImport(spec) {
  if (!spec.startsWith('./')) return null;
  const base = spec.slice(2);
  for (const candidate of [`${base}.tsx`, `${base}.ts`, base]) {
    if (fs.existsSync(path.join(nshUi, candidate))) return candidate;
  }
  return null;
}

function nshImportsOf(file) {
  const text = fs
    .readFileSync(path.join(nshUi, file), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1');
  const found = new Set();
  for (const match of text.matchAll(/\bfrom\s+["'](\.\/[^"']+)["']/g)) {
    const resolved = resolveNshImport(match[1]);
    if (resolved) found.add(resolved);
  }
  for (const match of text.matchAll(/\bimport\s+["'](\.\/[^"']+)["']/g)) {
    const resolved = resolveNshImport(match[1]);
    if (resolved) found.add(resolved);
  }
  return [...found].filter((imported) => imported !== 'theme.ts' && imported !== 'tokens.ts');
}

if (fs.existsSync(nshUi)) {
  const themeFiles = ['theme.ts', 'tokens.ts', 'theme.json'];
  for (const file of themeFiles) {
    if (!fs.existsSync(path.join(nshUi, file))) {
      throw new Error(`NSH components are installed with their theme, and ${file} does not exist in ${nshUi}.`);
    }
  }
  const themeEntries = themeFiles.map((file) => ({
    src: `crates/nsh-component/src/components/${file}`,
    target: file,
  }));

  const files = fs
    .readdirSync(nshUi)
    .filter((name) => name.endsWith('.tsx'))
    .sort();
  for (const file of files) {
    const module = file.replace(/\.tsx$/, '');
    const name = module.replace(/_/g, '-');
    if (nsh.components[name]) {
      throw new Error(`NSH components "${file}" and another file both map to the registry key "${name}".`);
    }
    nsh.components[name] = [
      ...closure(file, nshImportsOf).map((imported) => ({
        src: `crates/nsh-component/src/components/${imported}`,
        target: imported,
      })),
      ...themeEntries,
    ];
  }

  // The theme is also a catalog page: `add nsh theme` installs the token file
  // (and the mobile theme) without a component that imports it.
  nsh.components.theme = themeEntries.map((entry) => ({ ...entry }));

  // A block is a finished screen, not a single primitive. These entries copy
  // the screen beside the components it imports, so `add nsh settings-block`
  // installs a runnable composition instead of only the settings control.
  const nshDemos = path.join(root, 'crates/nsh-component/src/demos');
  const blockFiles = fs.existsSync(nshDemos)
    ? fs.readdirSync(nshDemos).filter((name) => name.endsWith('_block.tsx')).sort()
    : [];
  for (const file of blockFiles) {
    const name = file.replace(/\.tsx$/, '').replace(/_/g, '-');
    const source = fs.readFileSync(path.join(nshDemos, file), 'utf8');
    const deps = [...source.matchAll(/from\s+["']\.\.\/components\/([^"']+)["']/g)]
      .map((match) => match[1].replace(/_/g, '-'));
    const entries = [
      { src: `crates/nsh-component/src/demos/${file}`, target: file },
      ...deps.flatMap((dep) => {
        if (!nsh.components[dep]) {
          throw new Error(`NSH block "${name}" imports "${dep}", which has no registry entry.`);
        }
        return nsh.components[dep];
      }),
    ];
    const seen = new Set();
    nsh.components[name] = entries.filter((entry) => {
      if (seen.has(entry.target)) return false;
      seen.add(entry.target);
      return true;
    });
  }
}

const registry = {
  slint,
  egui: rust('src/components'),
  gpui,
  iced,
  nsh,
  quickgui: rust('src/components'),
};

fs.writeFileSync(
  path.join(root, 'registry/components.json'),
  `${JSON.stringify(registry, null, 2)}\n`,
);
const slugs = Object.fromEntries(
  Object.entries(registry).map(([name, framework]) => [
    name,
    Object.keys(framework.components).sort(),
  ]),
);
fs.writeFileSync(
  path.join(root, 'website/src/lib/registry-slugs.json'),
  `${JSON.stringify(slugs, null, 2)}\n`,
);
console.log(
  `slint components: ${Object.keys(slint.components).length}, icons: ${icons.length}, ` +
    `gpui blocks: ${GPUI_BLOCKS.length}, iced components: ${Object.keys(iced.components).length}, ` +
    `nsh components: ${Object.keys(nsh.components).length}`,
);
