#!/usr/bin/env node
// Generate the NSH icon map from the catalog's Lucide set.
//
//   node crates/nsh-component/scripts/gen-icons.mjs
//   node crates/nsh-component/scripts/gen-icons.mjs --check
//
// `crates/slint-component/ui/icons` is the catalog's authoritative icon set:
// every framework's Icon names come from it. NSH cannot draw SVG images, so each
// element is converted to SVG path data and drawn by `icon.tsx` with
// `Path2D` on a Canvas. The file is committed so installing `icon` needs no
// generation step.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const sourceDir = path.join(root, 'crates/slint-component/ui/icons');
const target = path.join(here, '../src/components/icons.ts');
const check = process.argv.includes('--check');

const attr = (text, name) => {
  const match = text.match(new RegExp(`\\b${name}\\s*=\\s*(?:"([^"]*)"|'([^']*)')`));
  return match ? (match[1] ?? match[2] ?? '') : undefined;
};

const shapes = (svg) => {
  const found = [];
  const push = (d) => {
    const value = String(d ?? '').trim();
    if (value) found.push(value);
  };

  for (const match of svg.matchAll(/<path\b[^>]*>/g)) {
    push(attr(match[0], 'd'));
  }
  for (const match of svg.matchAll(/<line\b[^>]*>/g)) {
    const x1 = Number(attr(match[0], 'x1'));
    const y1 = Number(attr(match[0], 'y1'));
    const x2 = Number(attr(match[0], 'x2'));
    const y2 = Number(attr(match[0], 'y2'));
    push(`M${x1} ${y1}L${x2} ${y2}`);
  }
  for (const match of svg.matchAll(/<polyline\b[^>]*>/g)) {
    const points = (attr(match[0], 'points') ?? '')
      .trim()
      .split(/[\s,]+/)
      .filter(Boolean);
    if (points.length >= 2) {
      push(`M${points[0]} ${points[1]}${points.slice(2).reduce((out, value, index) => (index % 2 === 0 ? `${out}L${value}` : `${out} ${value}`), '')}`);
    }
  }
  for (const match of svg.matchAll(/<polygon\b[^>]*>/g)) {
    const points = (attr(match[0], 'points') ?? '')
      .trim()
      .split(/[\s,]+/)
      .filter(Boolean);
    if (points.length >= 2) {
      push(`M${points[0]} ${points[1]}${points.slice(2).reduce((out, value, index) => (index % 2 === 0 ? `${out}L${value}` : `${out} ${value}`), '')}Z`);
    }
  }
  for (const match of svg.matchAll(/<circle\b[^>]*>/g)) {
    const cx = Number(attr(match[0], 'cx'));
    const cy = Number(attr(match[0], 'cy'));
    const r = Number(attr(match[0], 'r'));
    if (r > 0) push(`M${cx - r} ${cy}a${r} ${r} 0 1 0 ${r * 2} 0a${r} ${r} 0 1 0 ${-r * 2} 0`);
  }
  for (const match of svg.matchAll(/<ellipse\b[^>]*>/g)) {
    const cx = Number(attr(match[0], 'cx'));
    const cy = Number(attr(match[0], 'cy'));
    const rx = Number(attr(match[0], 'rx'));
    const ry = Number(attr(match[0], 'ry'));
    if (rx > 0 && ry > 0) push(`M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${rx * 2} 0a${rx} ${ry} 0 1 0 ${-rx * 2} 0`);
  }
  for (const match of svg.matchAll(/<rect\b[^>]*>/g)) {
    const x = Number(attr(match[0], 'x') ?? 0);
    const y = Number(attr(match[0], 'y') ?? 0);
    const width = Number(attr(match[0], 'width'));
    const height = Number(attr(match[0], 'height'));
    const rx = Math.min(Number(attr(match[0], 'rx') ?? 0), width / 2, height / 2);
    if (!(width > 0 && height > 0)) continue;
    if (rx <= 0) {
      push(`M${x} ${y}H${x + width}V${y + height}H${x}Z`);
    } else {
      push(
        `M${x + rx} ${y}H${x + width - rx}a${rx} ${rx} 0 0 1 ${rx} ${rx}` +
          `V${y + height - rx}a${rx} ${rx} 0 0 1 ${-rx} ${rx}` +
          `H${x + rx}a${rx} ${rx} 0 0 1 ${-rx} ${-rx}` +
          `V${y + rx}a${rx} ${rx} 0 0 1 ${rx} ${-rx}Z`,
      );
    }
  }
  return found;
};

const icons = {};
for (const name of fs.readdirSync(sourceDir).filter((file) => file.endsWith('.svg')).sort()) {
  const svg = fs.readFileSync(path.join(sourceDir, name), 'utf8');
  const paths = shapes(svg);
  if (paths.length === 0) {
    console.warn(`gen-icons: ${name} has no drawable shape; skipped`);
    continue;
  }
  // Lucide's stroke icons say `fill="none" stroke="currentColor"` on the root;
  // the few filled brand marks (GitHub) say neither. Keep the distinction so a
  // filled icon is not stroked into an outline.
  const filled = !/stroke\s*=\s*["']currentColor["']/.test(svg);
  icons[name.replace(/\.svg$/, '')] = paths.map((d) => (filled ? { d, fill: true } : { d }));
}

const banner = `// Generated by crates/nsh-component/scripts/gen-icons.mjs from
// crates/slint-component/ui/icons. Do not edit by hand: add the SVG to the
// catalog's icon set and run the script.
//
// Each entry is SVG path data, drawn by icon.tsx with Canvas and Path2D. A
// \`fill\` entry is a filled brand mark; the rest are Lucide strokes.
export interface IconShape {
  d: string;
  fill?: boolean;
}

export const ICONS: Record<string, IconShape[]> = `;
const file = `${banner}${JSON.stringify(icons, null, 2)};\n\nexport type IconName = keyof typeof ICONS;\n\nexport const ICON_NAMES = Object.keys(ICONS) as IconName[];\n`;

if (check) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== file) {
    console.error('gen-icons: src/components/icons.ts is stale; run node crates/nsh-component/scripts/gen-icons.mjs');
    process.exit(1);
  }
  console.log(`gen-icons: ${Object.keys(icons).length} icons verified`);
} else {
  fs.writeFileSync(target, file);
  console.log(`gen-icons: wrote ${Object.keys(icons).length} icons to ${path.relative(root, target)}`);
}
