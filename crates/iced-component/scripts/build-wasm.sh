#!/usr/bin/env bash
# Builds the gallery the website serves at `/iced-gallery`.
#
#   scripts/build-wasm.sh              debug, for working on a component
#   scripts/build-wasm.sh --release    what the site deploys
#
# The output is `www/dist`: the page, the wasm-bindgen glue and the module. The
# site serves that folder as it stands — in development through the middleware in
# `website/src/lib/wasm-middleware.js`, in production by copying it into the
# built site — so nothing here needs a bundler.
#
# The build runs inside `script/guard.sh`, the same cgroup cap the Slint gallery
# uses. A single rustc for iced peaks well above what a 14 GiB laptop can spare
# while the desktop is running, and without the cap the kernel swaps the whole
# session out before it considers killing the build.
set -euo pipefail

crate_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
root="$(cd "$crate_dir/../.." && pwd)"

profile="debug"
cargo_args=(build --manifest-path "$crate_dir/Cargo.toml" --target wasm32-unknown-unknown --lib)
target_dir="debug"
if [[ "${1:-}" == "--release" ]]; then
  profile="release"
  cargo_args+=(--release)
  target_dir="release"
fi

# A `cdylib` is what a page loads; `--lib` builds that plus the `rlib` the
# examples use, and the wasm-bindgen step picks the module out below.
echo "iced: building the gallery ($profile)"
"$root/script/guard.sh" cargo "${cargo_args[@]}"

wasm="$crate_dir/target/wasm32-unknown-unknown/$target_dir/iced_component.wasm"
if [[ ! -f "$wasm" ]]; then
  echo "iced: no module at $wasm" >&2
  exit 1
fi

# The bindings are generated by a CLI whose version must match the
# `wasm-bindgen` the module was compiled with; a mismatch is refused with a
# message naming the version to install, and it is worth repeating here because
# the fix is a `cargo install` rather than anything in this repository.
if ! command -v wasm-bindgen >/dev/null 2>&1; then
  echo "iced: wasm-bindgen is not installed." >&2
  echo "iced: cargo install -f wasm-bindgen-cli" >&2
  exit 1
fi

out="$crate_dir/www/dist"
mkdir -p "$out"
echo "iced: generating bindings into www/dist"
if ! wasm-bindgen "$wasm" --out-dir "$out" --target web --no-typescript; then
  echo "iced: the bindings were refused — usually a wasm-bindgen version mismatch." >&2
  echo "iced: the module wants $(grep -m1 -A1 'name = "wasm-bindgen"' "$crate_dir/Cargo.lock" | tail -1 | tr -dc '0-9.'), installed is $(wasm-bindgen --version | tr -dc '0-9.')." >&2
  echo "iced: cargo install -f wasm-bindgen-cli --version <the version above>" >&2
  exit 1
fi

# The page is static and is served from the same folder.
cp "$crate_dir/www/index.html" "$out/index.html"

# Smaller is a faster first paint, and wasm-opt is best effort: a refusal leaves
# the module rustc built rather than failing the build.
# shellcheck source=/dev/null
source "$root/script/optimize-wasm.sh"
optimize_wasm "$out/iced_component_bg.wasm"

echo "iced: gallery ready in crates/iced-component/www/dist"
echo "iced: make dev:website-iced serves it at /iced-gallery"
